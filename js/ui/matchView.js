    // Canvas Setup
    const canvas = container.querySelector("#match-canvas");
    const ctx = canvas ? canvas.getContext("2d") : null;

    function resizeCanvas() {
      if (!canvas) return;
      const rect = canvas.getBoundingClientRect();
      const dpr = window.devicePixelRatio || 1;
      const targetW = (rect.width > 0 ? rect.width : 360) * dpr;
      const targetH = (rect.height > 0 ? rect.height : 225) * dpr;
      if (canvas.width !== targetW || canvas.height !== targetH) {
        canvas.width = targetW;
        canvas.height = targetH;
      }
    }
    resizeCanvas();

    function drawPitch() {
      if (!ctx || !canvas) return;
      resizeCanvas();
      const w = canvas.width;
      const h = canvas.height;
      const dpr = window.devicePixelRatio || 1;

      // Césped
      ctx.fillStyle = "#166534";
      ctx.fillRect(0, 0, w, h);
      const stripes = 8;
      const stripeW = w / stripes;
      for (let i = 0; i < stripes; i += 2) {
        ctx.fillStyle = "#15803d";
        ctx.fillRect(i * stripeW, 0, stripeW, h);
      }

      // Líneas
      ctx.strokeStyle = "rgba(255, 255, 255, 0.4)";
      ctx.lineWidth = 2 * dpr;
      ctx.strokeRect(10, 10, w - 20, h - 20);
      ctx.beginPath();
      ctx.moveTo(w / 2, 10);
      ctx.lineTo(w / 2, h - 10);
      ctx.stroke();

      ctx.beginPath();
      ctx.arc(w / 2, h / 2, 35 * dpr, 0, Math.PI * 2);
      ctx.stroke();

      const boxW = 55 * dpr;
      const boxH = 90 * dpr;
      ctx.strokeRect(10, (h - boxH) / 2, boxW, boxH);
      ctx.strokeRect(w - 10 - boxW, (h - boxH) / 2, boxW, boxH);

      const state = simulator.getState();
      state.home2D.forEach(p => {
        const px = (p.curX / 100) * w;
        const py = (p.curY / 100) * h;
        ctx.beginPath();
        ctx.arc(px, py, 6 * dpr, 0, Math.PI * 2);
        ctx.fillStyle = homeTeam.primaryColor;
        ctx.fill();
        ctx.strokeStyle = "#ffffff";
        ctx.lineWidth = 1.5;
        ctx.stroke();
      });

      state.away2D.forEach(p => {
        const px = (p.curX / 100) * w;
        const py = (p.curY / 100) * h;
        ctx.beginPath();
        ctx.arc(px, py, 6 * dpr, 0, Math.PI * 2);
        ctx.fillStyle = awayTeam.primaryColor;
        ctx.fill();
        ctx.strokeStyle = "#ffffff";
        ctx.lineWidth = 1.5;
        ctx.stroke();
      });

      const bx = (state.ball.x / 100) * w;
      const by = (state.ball.y / 100) * h;
      ctx.beginPath();
      ctx.arc(bx, by, 4.5 * dpr, 0, Math.PI * 2);
      ctx.fillStyle = "#ffffff";
      ctx.fill();
      ctx.strokeStyle = "#000000";
      ctx.lineWidth = 1.5;
      ctx.stroke();

      if (!simulator.isFinished) {
        requestAnimationFrame(drawPitch);
      }
    }
    requestAnimationFrame(drawPitch);

